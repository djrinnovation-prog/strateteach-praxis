/**
 * index.ts — Worker entry point
 *
 * Polls pgmq(trade_signals) for signals from TradingView via Edge Function.
 * Executes market orders via BinanceAdapter.
 *
 * ── Queue message contract (WB1 v1.0 — frozen 2026-06-04) ────────────────────
 *   { schema_version: '1.0', bot_id: string, signal_id: string, side: 'buy'|'sell' }
 *   - schema_version : REQUIRED, must equal '1.0' — reject otherwise (F-02).
 *                      The field exists so a future format can never be
 *                      misread as v1.0; enforcing it is what makes it real.
 *   - symbol         : loaded from bots.trading_pair — never from message
 *   - client_order_id: generated by Worker (PRX_<nanoid(10)>) — never from message
 *   See Decision Log: "Queue Message Format v1.0" (supersedes Option A 2026-06-01)
 *
 * ── pgmq RPC wrappers (migration 007 — applied 2026-06-04) ────────────────────
 *   pgmq_read(queue_name, vt, qty)  → message rows
 *   pgmq_delete(queue_name, msg_id) → boolean
 *   The poll loop stays gated behind QUEUE_ENABLED until WB6 E1 validation.
 *
 * ── QUEUE_ENABLED (Decision 2026-06-03) ───────────────────────────────────────
 *   Optional env flag, default false. Controls whether the poll loop runs.
 *   false (Sprint 2): reconcile, log worker_queue_disabled once, stay alive idle.
 *   true  (Sprint 3): preflight pgmq_read (fail fast if missing), then poll.
 *
 * ── Boot sequence ─────────────────────────────────────────────────────────────
 *   1. Validate env (SUPABASE_URL, SUPABASE_SERVICE_ROLE_KEY, PRAXIS_IS_PRODUCTION,
 *      QUEUE_ENABLED; DOPPLER_ENVIRONMENT warn-only)
 *   2. Create Supabase client (service_role, no session persistence)
 *   3. Boot reconciliation — find stuck pending/unknown trades → reconciliation_jobs
 *   4. QUEUE_ENABLED=false → idle keep-alive; true → preflight + poll loop
 *      until SIGTERM / SIGINT
 *
 * ── processMessage steps ──────────────────────────────────────────────────────
 *   0.  Validate message shape
 *   1.  Fetch bot
 *   2.  Check bot.status === 'active'
 *   2.5 Guard: credential_id null → disable bot, ack (ENG-007)
 *   3.  Idempotency — UNIQUE(bot_id, signal_id); unknown → upsert recon_job
 *   3.5 Guard: unresolved unknown trades → ack=false, block bot (ENG-004)
 *   4a. Resolve user_exchange_credentials by bot.credential_id → vault_secret_id;
 *       gates: status='valid', not deleted, UUID-shaped pointer (F-01, 2026-06-11).
 *       Vault receives vault_secret_id — NEVER the credentials row id.
 *   4.  Build BinanceAdapter
 *   5.  Get market rules (symbol from bots.trading_pair)
 *   6.  Calculate quantity (BUY: minimum safe / SELL: 95% of free balance)
 *   7.  INSERT trades(pending) — BEFORE any exchange call
 *   8.  createOrder()
 *   9.  UPDATE trades(submitted|filled)
 *  10.  Error handling: three-way split (see below)
 *
 * ── Error classification ──────────────────────────────────────────────────────
 *   Immediate disable — ack, no threshold, credential → 'invalid', bot → 'error':
 *     VaultSecretNotFoundError → trade: failed, DLQ, disableCredentialAndBot
 *     ExchangeAuthError        → trade: failed, DLQ, disableCredentialAndBot
 *
 *   Threshold-based permanent — ack, failures++, circuit breaker at 5:
 *     ExchangeRejectedError    → trade: failed, DLQ, consecutive_failures++
 *
 *   Transient — inline fetchOrder attempted once (ENG-004, Option B):
 *     fetchOrder → filled|submitted|cancelled|failed  → update trade, ack=true
 *     fetchOrder → null (OrderNotFound)               → trade: failed, ack=true (no DLQ, no failures++)
 *     fetchOrder → throws transient                   → trade: unknown, reconciliation_job, ack=true
 *     DB errors (pre-INSERT)                          → no trade written, ack=false (retry)
 *
 *   UPDATE failure after createOrder success:
 *     → trade: unknown, reconciliation_job immediately, ack=true (don't risk duplicate order)
 *
 *   Skip — ack, no trade written:
 *     Malformed message shape
 *     Bot not found / not active / null credential
 *     Credential row missing / deleted / not-valid / malformed vault pointer
 *       → bot disabled, credential row UNTOUCHED (F-01)
 *     Duplicate signal (idempotency — terminal status)
 *     Unknown trade re-queued → upsert reconciliation_job, ack=true
 *     SELL with no sellable position
 *     Race-condition duplicate INSERT (23505 on bot_id+signal_id)
 *
 * ── Circuit breaker ───────────────────────────────────────────────────────────
 *   bots.consecutive_failures increments on ExchangeRejectedError only.
 *   >= MAX_CONSECUTIVE_FAILURES (5) → bot.status = 'error'. Manual reset required.
 *   Reset to 0 only on filled or submitted (NOT cancelled — ENG-008).
 *
 * ── ⚠️  POSITION AMBIGUITY RISK (ENG-004 — Decision Log 2026-06-02) ───────────
 *   WINDOW: createOrder() dispatched → fetchOrder() resolves (Step 8b)
 *
 *   During this window the exchange position state is unknown:
 *   the order may or may not have been submitted. If a second signal arrives
 *   during this window it is blocked by Step 3.5 (unknown trade guard),
 *   preventing double-exposure.
 *
 *   RESOLUTION — Option B (inline fetchOrder, decided 2026-06-02):
 *     createOrder() timeout → immediate fetchOrder(clientOrderId) once:
 *       filled|submitted|cancelled → resolve trade inline, ack, no recon job
 *       OrderNotFound (null)       → order never reached exchange, trade=failed, ack
 *       fetchOrder also times out  → trade=unknown, recon_job, bot blocked via 3.5
 *
 *   Only genuinely unresolvable trades (network outage across BOTH calls) enter
 *   reconciliation. Never ack a transient failure without either a resolved trade
 *   or a reconciliation_job — no silent unresolved position state allowed.
 *
 *   VISIBILITY TIMEOUT IMPACT:
 *   Inline fetchOrder adds a second exchange round-trip to worst-case duration.
 *   Formula revised: worst_case = T_vault + 2 × T_timeout + T_db + overhead
 *   Required: T_timeout ≤ 5000ms (set in BinanceAdapter) to stay within 30s VT.
 *   See Decision Log: "pgmq visibility_timeout — PENDING MEASUREMENT"
 *
 * ── Deferred to Sprint 3 (see Decision Log) ──────────────────────────────────
 *   Reconciliation setInterval(60s)
 *   Trade quantity: configurable position_size_pct
 *
 * ── Security (Decision Log 2026-05-31) ───────────────────────────────────────
 *   NEVER log: credentials, exchange objects, raw Vault values, account balances
 *   NEVER include credentialId in Error.message
 *   All logs: structured JSON, safe fields only
 *   SUPABASE_SERVICE_ROLE_KEY: Doppler only, never hardcoded
 */

