/**
 * Visibility timeout (seconds) — message is hidden from other consumers after
 * being read. Must exceed worst-case processing time; if processing exceeds VT, pgmq re-exposes the
 * message mid-flight (redelivery churn + spurious unknown/reconciliation — UNIQUE(bot_id,signal_id)
 * still prevents a double order, but the "read_ct stays 1" assumption breaks).
 *
 * M-16 (audit v3) — the OLD formula counted only 2 × T_exchange_timeout (createOrder + inline
 * fetchOrder) and understated the worst case. A COLD-CACHE message on a first delivery serially runs up
 * to FIVE 5s exchange calls: getMarketRules(loadMarkets) + fetchBalance + fetchPrice + createOrder +
 * inline fetchOrder, plus multiple Vault fetches + DB round-trips:
 *   worst_case ≈ 5 × T_exchange_timeout + 3 × T_vault + T_db + overhead
 *              ≈ 5 × 5000ms + ~360ms + ~200ms + ~100ms ≈ 25.7s
 *   visibility_timeout = worst_case + ~15s safety buffer ≈ 40–45s
 * So the safe DEFAULT is 45s (raised from 30s). Mitigations that shrink the worst case: warm the
 * market-rules cache at boot (removes one 5s call) and keep T_exchange_timeout ≤ 5000ms.
 *
 * The LIVE value is env-set (QUEUE_VISIBILITY_TIMEOUT_S via Doppler/Railway — an operator action); this
 * default only applies when that var is unset. See Decision Log: "pgmq visibility_timeout".
 */
const VISIBILITY_TIMEOUT_S = parseInt(process.env.QUEUE_VISIBILITY_TIMEOUT_S ?? '45', 10)

/** Poll interval when queue is empty (ms). */
