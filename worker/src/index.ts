// ─── Env validation ───────────────────────────────────────────────────────────

function validateEnv(): {
  supabaseUrl:    string
  serviceRoleKey: string
  isProduction:   boolean
  queueEnabled:   boolean
} {
  // DOPPLER_ENVIRONMENT is set by `doppler run` locally but NOT by Doppler's Railway
  // integration (which syncs secrets as plain env vars, without this key).
  // Log it if present; warn-only if absent — never block startup on its absence.
  if (process.env.DOPPLER_ENVIRONMENT) {
    console.log(JSON.stringify({
      event:       'startup_env',
      environment: process.env.DOPPLER_ENVIRONMENT, // 'dev' | 'staging' | 'production' — not a secret
    }))
  } else {
    console.log(JSON.stringify({
      event:       'startup_env',
      environment: 'unknown',
      hint:        'DOPPLER_ENVIRONMENT not set — expected on Railway (Doppler integration), warn-only in local dev',
    }))
  }

  const supabaseUrl     = process.env.SUPABASE_URL
  const serviceRoleKey  = process.env.SUPABASE_SERVICE_ROLE_KEY
  const isProductionRaw = process.env.PRAXIS_IS_PRODUCTION

  const missing = [
    !supabaseUrl      && 'SUPABASE_URL',
    !serviceRoleKey   && 'SUPABASE_SERVICE_ROLE_KEY',
    !isProductionRaw  && 'PRAXIS_IS_PRODUCTION',
  ].filter((x): x is string => typeof x === 'string')

  if (missing.length > 0) {
    console.error(JSON.stringify({ event: 'startup_error', reason: 'missing_env_vars', missing }))
    process.exit(1)
  }

  if (isProductionRaw !== 'true' && isProductionRaw !== 'false') {
    console.error(JSON.stringify({
      event:  'startup_error',
      reason: 'invalid_env_var',
      var:    'PRAXIS_IS_PRODUCTION',
      hint:   'must be exactly "true" or "false"',
    }))
    process.exit(1)
  }

  // QUEUE_ENABLED gates the poll loop (Decision 2026-06-03).
  //   Optional — absent defaults to false (safe state: Worker does not trade).
  //   Strict-if-present: a typo like "1" or "yes" must NOT silently disable
  //   trading in production, so reject anything other than "true"/"false".
  //   Default false is correct for the Sprint 2 Railway deploy: the pgmq_read
  //   RPC wrapper does not exist yet, so the poll loop would only spam
  //   queue_read_error. Set "true" in Sprint 3 once the wrapper migration lands.
  const queueEnabledRaw = process.env.QUEUE_ENABLED
  if (
    queueEnabledRaw !== undefined &&
    queueEnabledRaw !== 'true' &&
    queueEnabledRaw !== 'false'
  ) {
    console.error(JSON.stringify({
      event:  'startup_error',
      reason: 'invalid_env_var',
      var:    'QUEUE_ENABLED',
      hint:   'must be exactly "true" or "false" if set (absent → false)',
    }))
    process.exit(1)
  }

  // A1 Option B: exchange egress via a fixed-IP proxy. Acknowledge PRESENCE only (the value is a SECRET — never
  // logged). Production fail-closed is enforced per-message BEFORE building the adapter (processMessage Step 4b +
  // reconciliation defaultAdapterFor) + the BinanceAdapter constructor invariant — NOT a hard startup exit (so a
  // prod worker still boots for read-only reconciliation/observability, but never trades/egresses without a proxy).
  console.log(JSON.stringify({
    event: 'startup_env',
    exchange_proxy_configured: Boolean(process.env.EXCHANGE_HTTPS_PROXY?.trim()),
    exchange_egress_mode: egressModeLabel(resolveEgress(process.env)), // B0: 'proxy' | 'native' | 'unset'
  }))

  return {
    supabaseUrl:    supabaseUrl!,
    serviceRoleKey: serviceRoleKey!,
    isProduction:   isProductionRaw === 'true',
    queueEnabled:   queueEnabledRaw === 'true',
  }
}

// ─── Boot reconciliation ──────────────────────────────────────────────────────

/**
 * Finds trades stuck in 'pending' or 'unknown' from before this Worker instance
 * started and inserts reconciliation_jobs for triage.
 *
 * 'pending': Worker crashed after INSERT trades(pending) but before createOrder.
 *   The exchange has no order. Trade must be marked failed or re-attempted.
 *
 * 'unknown': Worker crashed after createOrder (exchange may have the order) but
 *   before UPDATE trades(submitted/filled). Must call fetchOrder to reconcile.
 *
 * Both cases require human or automated triage — reconciliation_jobs is the handoff.
 *
 * setInterval(60s) runtime scan deferred to Sprint 3.
 * See Decision Log: "Reconciliation worker — setInterval(60s) design, cap, and coordination"
 */
async function runBootReconciliation(supabase: SupabaseClient): Promise<number | null> {
  const threshold = new Date(
    Date.now() - RECONCILIATION_THRESHOLD_SECONDS * 1000,
  ).toISOString()

  const { data: stuckTrades, error } = await supabase
    .from('trades')
    .select('id, bot_id, signal_id, status')
    .in('status', ['pending', 'unknown'])
    .lt('created_at', threshold)
    .is('deleted_at', null)

  if (error) {
    console.error(JSON.stringify({
      event: 'boot_reconciliation_query_error',
      error: error.code,
    }))
    return null   // unknown — boot query failed (worker_status records null = unknown)
  }

  const count = stuckTrades?.length ?? 0
  console.log(JSON.stringify({ event: 'boot_reconciliation_complete', stuck_count: count }))

  if (count === 0) return 0

  for (const trade of stuckTrades!) {
    const { error: upsertError } = await supabase
      .from('reconciliation_jobs')
      .upsert(
        { trade_id: trade.id },
        { onConflict: 'trade_id', ignoreDuplicates: true },
      )

    if (upsertError) {
      console.error(JSON.stringify({
        event:    'reconciliation_job_upsert_error',
        trade_id: trade.id,
        status:   trade.status,
        error:    upsertError.code,
      }))
    } else {
      console.log(JSON.stringify({
        event:    'reconciliation_job_created',
        trade_id: trade.id,
        status:   trade.status,
      }))
    }
  }

  return count
}

