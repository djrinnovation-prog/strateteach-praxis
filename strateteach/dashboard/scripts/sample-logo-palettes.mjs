// Build-time sampler: extract the EXACT per-skin letter colours from the real logo art
// (public/logo-{skin}.png) and bake them into src/lib/logoPalettes.ts, so CarvedTitle
// uses pixel-exact brand colours per skin instead of an eyeballed palette.
//
// Each logo is the "StrateTeach" wordmark swept across that skin's tonal fan, with a 3D
// extrusion (a DARKER copy down-right) + a near-WHITE cut stroke. We sample the FRONT-FACE
// colour across the word in K evenly-spaced vertical bands: within each band we drop
// transparent, near-white (stroke) and very-dark (extrusion) pixels, then take the median
// of the brightest remaining tones (the lit front face). K bands → an ordered tonal palette
// that CarvedTitle cycles for any title. Run in Docker: `node scripts/sample-logo-palettes.mjs`.
import { PNG } from "pngjs";
import { readFileSync, writeFileSync } from "node:fs";

const SKINS = { navy: "logo-navy.png", peach: "logo-peach.png", amber: "logo-nude.png", aurora: "logo-sea.png" };
const K = 14;                 // bands → palette length per skin (fine enough to track each letter's colour)

function rgbToHsl(r, g, b) {
  r /= 255; g /= 255; b /= 255;
  const max = Math.max(r, g, b), min = Math.min(r, g, b);
  let h = 0, s = 0; const l = (max + min) / 2;
  if (max !== min) {
    const d = max - min;
    s = l > 0.5 ? d / (2 - max - min) : d / (max + min);
    if (max === r) h = (g - b) / d + (g < b ? 6 : 0);
    else if (max === g) h = (b - r) / d + 2;
    else h = (r - g) / d + 4;
    h /= 6;
  }
  return [h, s, l];
}
const toHex = (r, g, b) => "#" + [r, g, b].map((v) => Math.max(0, Math.min(255, Math.round(v))).toString(16).padStart(2, "0")).join("");
function median(arr) { const s = [...arr].sort((a, b) => a - b); return s[Math.floor(s.length / 2)] || 0; }

function sample(file) {
  const png = PNG.sync.read(readFileSync(new URL(`../public/${file}`, import.meta.url)));
  const { width, height, data } = png;
  const at = (x, y) => { const i = (y * width + x) * 4; return [data[i], data[i + 1], data[i + 2], data[i + 3]]; };
  // opaque horizontal extent of the wordmark
  let minX = width, maxX = 0;
  for (let x = 0; x < width; x++) {
    let any = false;
    for (let y = 0; y < height; y += 3) { if (at(x, y)[3] > 180) { any = true; break; } }
    if (any) { if (x < minX) minX = x; if (x > maxX) maxX = x; }
  }
  // Sample K bands across the wordmark, but read only each band's CENTRE 50% of columns
  // (the letter body, away from the inter-letter boundaries) → each palette entry tracks
  // one letter's true colour closely. A 3D-rendered wordmark can't be cleanly segmented
  // per glyph (the extrusion bridges the gaps), so centre-of-band is the tight approach.
  const isFace = (r, g, b, a) => { if (a < 200) return false; const [, s, l] = rgbToHsl(r, g, b); if (l > 0.9 && s < 0.25) return false; if (l < 0.14) return false; return true; };
  const bandW = (maxX - minX) / K;
  const pal = [];
  for (let k = 0; k < K; k++) {
    const c0 = minX + k * bandW, c1 = minX + (k + 1) * bandW;
    const x0 = Math.floor(c0 + bandW * 0.25), x1 = Math.ceil(c1 - bandW * 0.25);  // centre 50%
    const cand = [];
    for (let x = x0; x < x1; x++) for (let y = 0; y < height; y += 2) {
      const [r, g, b, a] = at(x, y);
      if (!isFace(r, g, b, a)) continue;
      const [, s, l] = rgbToHsl(r, g, b);
      cand.push({ r, g, b, l, s });
    }
    if (!cand.length) { pal.push("#888888"); continue; }
    // favour the lit + saturated FACE (drops the darker extrusion, keeps a vivid letter).
    cand.sort((a, b) => (b.l * 0.55 + b.s * 0.45) - (a.l * 0.55 + a.s * 0.45));
    const face = cand.slice(0, Math.max(1, Math.floor(cand.length * 0.4)));
    pal.push(toHex(median(face.map((p) => p.r)), median(face.map((p) => p.g)), median(face.map((p) => p.b))));
  }
  return pal;
}

const out = {};
for (const [skin, file] of Object.entries(SKINS)) { out[skin] = sample(file); console.log(skin.padEnd(8), out[skin].join(" ")); }

const ts = `// AUTO-GENERATED by scripts/sample-logo-palettes.mjs — do not edit by hand.
// Pixel-exact per-skin letter colours sampled from public/logo-{skin}.png (the real logo
// art), used by CarvedTitle so each screen's carved title matches TODAY's logo per skin.
export type SkinKey = "navy" | "peach" | "amber" | "aurora";
export const LOGO_PALETTES: Record<SkinKey, string[]> = ${JSON.stringify(out, null, 2)};
`;
writeFileSync(new URL("../src/lib/logoPalettes.ts", import.meta.url), ts);
console.log("\nwrote src/lib/logoPalettes.ts");
